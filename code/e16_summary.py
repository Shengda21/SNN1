"""Summarize E16-E18 members (new file).

python e16_summary.py --platform sim     (or sarcos; default: both)

Reads every <runs>/<platform>/w1*/config.json (completed members only) plus, as
reference rows, the original members of runs25 needed by E16-E18 (dm_* incl. the STE
common limit, ba_<strong>_*, bn_mlp_*; source = runs25). Writes
  ../results/<platform>/e16_members.csv   one row per member
  ../results/<platform>/e16_agg.csv       mean / sd / n over seeds per configuration
nMSE (as in the manuscript): standardized units, mean over rows of (1/7) sum_l (pred - y)_l^2,
computed on the test role for every frozen condition (sim: also test_P1 under N) and on the
development role under N (dev_nmse_N, equal to best_dev up to float rounding).
Quick plane coordinates on the test role (section 2.1 of the plan; standardized units,
row average, P_y = mean_rows (1/7)|y|^2): beta_<cond> = <F,Y>/P_y, nu2_<cond> = |F|^2 - beta^2 P_y,
slope_<cond> = <F,Y>/|F|^2, and for noisy conditions the forward response
r_<cond> = mean_rows |f(x+delta) - f(x)| / |delta| with delta regenerated by apply_condition
(same fixed seeds as the stored predictions). These are preliminary; E15 owns the final metrics.
"""
import argparse
import csv
import glob
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from e16_surrogates import hwhm_from_param

RUNS = os.path.join(HERE, "..", "runs")
RUNS25 = os.path.join(HERE, "..", "runs25")
RESULTS = os.path.join(HERE, "..", "results")
FAM_OF_ORIG = {"triangular": "tri", "sigmoid": "sig", "atan": "atan", "sre": "sre", "ste": "ste"}
META = ["member_id", "source", "block", "stage", "experiment", "family", "hwhm", "seed", "placement",
        "hwhm_layers", "peak_normalized", "peak", "surrogate", "width", "membrane_noise", "aug_scale",
        "aug_sigma", "activation", "model_class", "detach_reset", "n_params", "best_epoch", "epochs_run", "train_time_s",
        "best_dev", "spk_l1", "spk_l2", "spk_l3"]
GROUP = ["source", "block", "family", "hwhm", "placement", "peak_normalized", "membrane_noise", "aug_scale",
         "activation", "detach_reset"]


def load_data(platform):
    if platform == "sarcos":
        from sarcos.data import load_sarcos, apply_condition
        D = load_sarcos(os.path.join(HERE, ".."), None)
    else:
        from sim.data import load_sim, apply_condition
        D = load_sim(os.path.join(HERE, "..", "data_sim"))
    return D, apply_condition


def plane(P, Y):
    P = P.astype(np.float64)
    py = float(np.mean(np.sum(Y * Y, 1)) / Y.shape[1])
    fy = float(np.mean(np.sum(P * Y, 1)) / Y.shape[1])
    ff = float(np.mean(np.sum(P * P, 1)) / Y.shape[1])
    b = fy / py
    return b, ff - b * b * py, fy / ff


def nmse(P, Y):
    return float(np.mean(np.sum((P.astype(np.float64) - Y) ** 2, 1) / Y.shape[1]))


def ref_rows(platform, frozen):
    """Original members used as references (STE limit, original widths, B-A, B-N)."""
    strong = frozen["strong_surrogate"]
    out = []
    pats = ["dm_*_s[0-9]", f"ba_{strong}_s[0-9]", "bn_mlp_s[0-9]"]
    for pat in pats:
        for d in sorted(glob.glob(os.path.join(RUNS25, platform, pat))):
            if os.path.exists(os.path.join(d, "config.json")):
                out.append(d)
    return out


def row_for(d, source, Y, conds, platform, deltas):
    cfg = json.load(open(os.path.join(d, "config.json")))
    r = {k: cfg.get(k) for k in META}
    r["source"] = source
    spk = cfg.get("spikes_per_sample_per_layer_dev") or [None] * 3
    r["spk_l1"], r["spk_l2"], r["spk_l3"] = spk
    if source == "runs25":
        s = cfg.get("surrogate")
        if s == "none":
            r.update(family=None, hwhm=None, activation="relu", model_class="MLP", peak_normalized=None)
        else:
            fam = FAM_OF_ORIG.get(s)
            r["family"] = fam
            r["hwhm"] = math.inf if fam == "ste" else hwhm_from_param(fam, cfg["width"])
            r["peak_normalized"] = fam in ("tri", "sre", "ste")
            r["peak"] = {"sig": (cfg["width"] or 0) / 4.0, "atan": (cfg["width"] or 0) / 2.0}.get(fam, 1.0)
            r["activation"] = "spike"; r["model_class"] = "SNN"
        r["membrane_noise"] = 0.0
        r["aug_scale"] = 1.0 if (cfg.get("aug_sigma") or 0.0) > 0 else 0.0
        r["stage"] = "runs25"
    if r.get("family") == "ste" and r.get("hwhm") is None:
        r["hwhm"] = math.inf
    r["detach_reset"] = bool(cfg.get("detach_reset", False))
    if isinstance(r.get("hwhm_layers"), list):
        r["hwhm_layers"] = "/".join(f"{x:g}" for x in r["hwhm_layers"])
    fN = os.path.join(d, "pred_test_N.npy")
    PN = np.load(fN).astype(np.float64) if os.path.exists(fN) else None
    for cond in conds:
        f = os.path.join(d, f"pred_test_{cond.replace(':', '_')}.npy")
        if not os.path.exists(f):
            r[f"test_nmse_{cond}"] = None
            continue
        P = np.load(f)
        r[f"test_nmse_{cond}"] = nmse(P, Y["test"])
        r[f"beta_{cond}"], r[f"nu2_{cond}"], r[f"slope_{cond}"] = plane(P, Y["test"])
        if cond != "N" and PN is not None:
            r[f"r_{cond}"] = float(np.mean(np.linalg.norm(P - PN, axis=1) / deltas[cond]))
    if platform == "sim":
        f = os.path.join(d, "pred_test_P1_N.npy")
        r["test_P1_nmse_N"] = nmse(np.load(f), Y["test_P1"]) if os.path.exists(f) else None
    f = os.path.join(d, "pred_dev_N.npy")
    r["dev_nmse_N"] = nmse(np.load(f), Y["dev"]) if os.path.exists(f) else None
    return r


def summarize(platform):
    frozen = json.load(open(os.path.join(RUNS25, platform, "frozen.json")))
    conds = frozen["conds"]
    D, apply_condition = load_data(platform)
    Y = D["Y"]
    deltas = {}
    for c in conds:
        if c != "N":
            dl = apply_condition(D["X"]["test"], "test", c).astype(np.float64) - D["X"]["test"]
            deltas[c] = np.maximum(np.linalg.norm(dl, axis=1), 1e-12)
    rows = []
    for d in sorted(glob.glob(os.path.join(RUNS, platform, "w1*"))):
        if os.path.exists(os.path.join(d, "config.json")):
            rows.append(row_for(d, "new", Y, conds, platform, deltas))
    n_new = len(rows)
    for d in ref_rows(platform, frozen):
        rows.append(row_for(d, "runs25", Y, conds, platform, deltas))
    metric_cols = [f"test_nmse_{c}" for c in conds] + (["test_P1_nmse_N"] if platform == "sim" else []) + ["dev_nmse_N"]
    metric_cols += [f"{q}_{c}" for c in conds for q in ("beta", "nu2", "slope")]
    metric_cols += [f"r_{c}" for c in conds if c != "N"]
    cols = META + metric_cols
    os.makedirs(os.path.join(RESULTS, platform), exist_ok=True)
    fm = os.path.join(RESULTS, platform, "e16_members.csv")
    with open(fm, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow(r)
    # aggregate over seeds
    groups = {}
    for r in rows:
        key = tuple(str(r.get(k)) for k in GROUP)
        groups.setdefault(key, []).append(r)
    agg_cols = GROUP + ["n", "seeds"] + [f"{m}_{s}" for m in ["best_dev"] + metric_cols for s in ("mean", "sd")]
    fa = os.path.join(RESULTS, platform, "e16_agg.csv")
    with open(fa, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=agg_cols)
        w.writeheader()
        for key, rs in sorted(groups.items()):
            a = dict(zip(GROUP, key)); a["n"] = len(rs)
            a["seeds"] = " ".join(str(r["seed"]) for r in sorted(rs, key=lambda r: r["seed"]))
            for m in ["best_dev"] + metric_cols:
                v = np.array([r[m] for r in rs if r.get(m) is not None], float)
                a[f"{m}_mean"] = float(v.mean()) if len(v) else None
                a[f"{m}_sd"] = float(v.std(ddof=1)) if len(v) > 1 else None
            w.writerow(a)
    print(f"{platform}: {n_new} new members, {len(rows) - n_new} reference rows -> {fm}, {fa}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--platform", default="sim,sarcos")
    args = ap.parse_args()
    for p in args.platform.split(","):
        summarize(p)


if __name__ == "__main__":
    main()
